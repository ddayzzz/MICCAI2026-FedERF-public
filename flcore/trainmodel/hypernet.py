import torch
import torch.nn as nn
import torch.nn.functional as F


class FunctionalLoRALinear(nn.Module):
    """
    一个“空壳”LoRA层。
    它不包含可训练的 LoRA 参数 (A, B)，而是依赖 forward 时传入的 generated_weights。
    """

    def __init__(self, original_layer, name, rank=8, alpha=16):
        super().__init__()
        self.original_layer = original_layer  # 冻结的原始线性层 (如 Attention 的 q, v)
        self.rank = rank
        self.scaling = alpha / rank
        self.name = name

    def forward(self, x, param_dict=None):
        """
        x: [batch, seq_len, in_dim]
        lora_A: 由超网络生成的矩阵 [in_dim, rank]
        lora_B: 由超网络生成的矩阵 [rank, out_dim]
        """
        # 1. 原始路径 (Frozen)
        out_frozen = self.original_layer(x)
        if param_dict is not None:
            lora_A = param_dict[f'{self.name}.lora_A']
            lora_B = param_dict[f'{self.name}.lora_B']
            # 2. LoRA 路径 (Generated)
            # 公式: x @ A @ B * scale
            # 注意: 如果 lora_B 是 [rank, out_dim]，则 x@A -> [batch, rank], result@B -> [batch, out_dim]
            # lora_out = (x @ lora_A) @ lora_B
            lora_out = F.linear(F.linear(x, lora_A.T, bias=None), lora_B.T, bias=None)

            return out_frozen + lora_out * self.scaling
        else:
            return out_frozen


class MoEFunctionalLoRA(nn.Module):
    def __init__(self, name, original_layer, rank=8, alpha=16):
        super().__init__()
        self.original_layer = original_layer  # Frozen backbone layer
        self.scaling = alpha / rank
        self.rank  = rank
        self.name = name

        self.in_features = original_layer.in_features
        self.out_features = original_layer.out_features
        self.lora_A = nn.Parameter(torch.randn(self.in_features, self.rank))
        self.lora_B = nn.Parameter(torch.randn(self.rank, self.out_features))


    def forward(self, x, expert_weights_list=None, routing_scores=None):
        """
        x: [batch, seq, in_dim]
        expert_weights_list: List of (lora_A, lora_B) tuples generated by Hypernet
                             List length = K (num experts)
        routing_scores: [batch, K] - 针对每个样本的专家权重
        """
        # 1. 原始路径 (Base Path)
        out_base = self.original_layer(x)

        if expert_weights_list is not None:
            # 2. 专家路径 (Experts Path)
            moe_out = 0

            # 遍历所有专家 (为了显存优化，可以使用循环；极致速度可用 bmm)
            for i, exp_param_dict in enumerate(expert_weights_list):
                # lora_A: [in, r], lora_B: [r, out]
                # 计算第 i 个专家的输出: x @ A @ B
                lora_A = exp_param_dict[f'{self.name}.lora_A']
                lora_B = exp_param_dict[f'{self.name}.lora_B']
                expert_out = (x @ lora_A) @ lora_B

                # 加权累加: score[i] * expert_out
                # routing_scores[:, i] shape is [batch], need [batch, 1, 1]
                w = routing_scores[:, i].view(-1, 1, 1)
                moe_out += w * expert_out

            student_out = (x @ self.lora_A) @ self.lora_B

            # 加权累加: score[i] * expert_out
            # routing_scores[:, i] shape is [batch], need [batch, 1, 1]
            w1 = routing_scores[:, -1].view(-1, 1, 1)
            moe_out += w1 * student_out

            return out_base + moe_out * self.scaling
        else:
            return out_base

    def register_router(self, num_experts):
        router = nn.Sequential(
            nn.Linear(512, 128),
            nn.ReLU(),
            nn.Linear(128, num_experts),
            nn.Softmax(dim=1)
        )
        self.register_module("router", router)

    def compute_route_weights(self, input_protos):
        pass

class Prototype2LoRA_Hypernet(nn.Module):
    def __init__(self, prototype_dim, target_shapes):
        """
        prototype_dim: 原型向量的维度 (例如 1024, 即 WSI feature dim)
        target_shapes: 需要生成的 LoRA 矩阵形状列表 [(in1, r), (r, out1), (in2, r)...]
        """
        super().__init__()
        self.target_shapes = target_shapes

        # 计算所有 LoRA 矩阵展平后的总参数量
        self.total_params = 0
        for shape in target_shapes:
            self.total_params += shape[0] * shape[1]

        # 生成器网络 (MLP)
        # 输入: 原型 (Task Descriptor) -> 输出: 所有 LoRA 参数
        self.generator = nn.Sequential(
            nn.Linear(prototype_dim, 256),
            nn.ReLU(),
            nn.Linear(256, 512),
            nn.ReLU(),
            nn.Linear(512, self.total_params)
        )

    def forward(self, prototype):
        # 1. 生成扁平化的参数向量
        flat_params = self.generator(prototype)

        # 2. 切割并重塑为具体的 LoRA 矩阵
        generated_weights = []
        start_idx = 0
        for shape in self.target_shapes:
            size = shape[0] * shape[1]
            weight = flat_params[start_idx: start_idx + size]
            # Reshape 为 [in, r] 或 [r, out]
            weight = weight.view(shape)
            generated_weights.append(weight)
            start_idx += size

        return generated_weights

